// Concatenates every migration, in filename order, into one file that can be
// pasted into the Supabase SQL Editor in a single operation.
//
// Why this exists: DDL cannot be executed with the anon or service_role key
// (both are PostgREST API keys, not Postgres credentials), and the Supabase CLI
// cannot link this project from the signed-in account. The SQL Editor runs as
// the database owner, so it is the one remaining path that does not require the
// database password.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import crypto from 'node:crypto';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const MIG = path.join(ROOT, 'supabase', 'migrations');
const OUT = path.join(ROOT, 'supabase', 'apply_all.sql');

const files = readdirSync(MIG).filter((f) => f.endsWith('.sql')).sort();
const sha = (s) => crypto.createHash('sha256').update(s).digest('hex').slice(0, 16);

const chunks = [];

chunks.push(`-- =====================================================================
-- CONSOLIDATED MIGRATION BUNDLE  (generated by tool/build_bundle.mjs)
-- =====================================================================
-- HOW TO APPLY
--   Supabase Dashboard -> SQL Editor -> New query -> paste this whole file -> Run
--
-- Contains ${files.length} migrations, applied in order:
${files.map((f, i) => `--   ${String(i + 1).padStart(2, '0')}. ${f}`).join('\n')}
--
-- SAFETY
--   * Every statement is idempotent. Re-running this file changes nothing.
--     Verified by applying the chain twice against PostgreSQL 18 and comparing
--     table / column / policy / index / trigger counts: all stable.
--   * Nothing is dropped. The existing prototype tables (companies, invoices,
--     restricted_drug_logs, stock_transfers) are RENAMED to <name>_legacy_v0,
--     so every current row stays queryable.
--   * The 7 rows in "invoices" all have companyId = NULL, so there is no correct
--     tenant to attribute them to. They are NOT copied into "sales"; they remain
--     intact in invoices_legacy_v0. To attach them to a tenant later:
--         SET app.legacy_target_tenant = '<tenant-uuid>';
--     then re-run the 009 section.
--
-- AFTER RUNNING, verify from this machine with:
--     node tool/verify_live.mjs
-- =====================================================================
`);

for (const f of files) {
  const sql = readFileSync(path.join(MIG, f), 'utf8').replace(/\r\n/g, '\n').trimEnd();
  chunks.push(`
-- =====================================================================
-- BEGIN ${f}
-- =====================================================================
${sql}
-- =====================================================================
-- END ${f}
-- =====================================================================
`);
}

const ledger = files
  .map((f) => `    ('${f}', '${sha(readFileSync(path.join(MIG, f), 'utf8'))}')`)
  .join(',\n');

chunks.push(`
-- =====================================================================
-- Record what was applied so tool/apply_migrations.mjs will not re-run these
-- if a database credential is supplied later.
-- =====================================================================
CREATE TABLE IF NOT EXISTS _migrations (
    filename   TEXT PRIMARY KEY,
    checksum   TEXT NOT NULL,
    applied_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

INSERT INTO _migrations (filename, checksum) VALUES
${ledger}
ON CONFLICT (filename) DO UPDATE
   SET checksum = EXCLUDED.checksum, applied_at = CURRENT_TIMESTAMP;

-- =====================================================================
-- Fail loudly if anything the billing code depends on is missing.
-- =====================================================================
DO $verify$
DECLARE
    missing TEXT := '';
BEGIN
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns
                   WHERE table_schema='public' AND table_name='sale_items'
                     AND column_name='tenant_id') THEN
        missing := missing || ' sale_items.tenant_id';
    END IF;

    IF NOT EXISTS (SELECT 1 FROM information_schema.columns
                   WHERE table_schema='public' AND table_name='sales'
                     AND column_name='billing_type') THEN
        missing := missing || ' sales.billing_type';
    END IF;

    IF NOT EXISTS (SELECT 1 FROM information_schema.columns
                   WHERE table_schema='public' AND table_name='sales'
                     AND column_name='authorized_pharmacist_id') THEN
        missing := missing || ' sales.authorized_pharmacist_id';
    END IF;

    IF NOT EXISTS (SELECT 1 FROM information_schema.views
                   WHERE table_schema='public' AND table_name='near_expiry_stock') THEN
        missing := missing || ' near_expiry_stock';
    END IF;

    IF NOT EXISTS (SELECT 1 FROM information_schema.tables
                   WHERE table_schema='public' AND table_name='pharmacists') THEN
        missing := missing || ' pharmacists';
    END IF;

    IF missing <> '' THEN
        RAISE EXCEPTION 'Migration incomplete, missing:%', missing;
    END IF;

    RAISE NOTICE 'SUCCESS: all migrations applied, required billing objects present.';
END $verify$;
`);

const out = chunks.join('\n');
writeFileSync(OUT, out, 'utf8');
console.log(`wrote ${path.relative(ROOT, OUT).replace(/\\/g, '/')}`);
console.log(`  migrations : ${files.length}`);
console.log(`  size       : ${out.length} bytes`);
console.log(`  lines      : ${out.split('\n').length}`);
